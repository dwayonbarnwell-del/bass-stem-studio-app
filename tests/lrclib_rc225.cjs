const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const js=fs.readFileSync(path.join(__dirname,'../ai-source/lrclib.js'),'utf8');
const context={window:{},document:{readyState:'loading',addEventListener(){}},console};
vm.runInNewContext(js,context);
const parse=context.window.BassLRCLIB.parseTimed;
let lines=parse('[00:01.00] First\n[00:02.50] Second\n[00:03.00] \n[00:09.00] Third',11);
assert.equal(lines.length,3);
assert.equal(lines[0].start,1);assert.equal(lines[0].end,2.5);
assert.equal(lines[1].end,3);assert.equal(lines[2].end,11);
lines=parse('[offset:+1000]\n[00:01.000] First\n[00:03.000] Later',12);
assert.equal(lines[0].start,2);
assert.equal(parse('[ar:author]',20).length,0);
assert.equal(parse('[00:01.00] Out',.5).length,0);
const app=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert(app.includes('./ai-source/lrclib.js'));
assert(app.includes('importTimedLines'));
assert(app.includes('songInfo'));
assert(app.includes("lyrics:window.BassLyrics?.exportData()||[]"));
assert(!js.includes('/api/v1/analyze'));
console.log('PASS: LRCLIB timing, opt-in integration and existing project persistence.');
