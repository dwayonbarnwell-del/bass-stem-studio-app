'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const dir=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(dir,'song-reference/chords.js'),'utf8');
const lib=fs.readFileSync(path.join(dir,'library-source/library.js'),'utf8');
const html=fs.readFileSync(path.join(dir,'index.html'),'utf8');
const dataset=JSON.parse(fs.readFileSync(path.join(dir,'song-reference/data.js'),'utf8').replace(/^window\.BassSongReferenceData=/,'').replace(/;\s*$/,''));
let checks=0;
function ok(v,msg){assert.ok(v,msg);checks++;}
ok(dataset.songs.length===850,'retains 850 entries');
ok(dataset.songs.filter(s=>s.sections?.some(p=>String(p.chords||'').trim())).length===565,'565 progressions');
ok(html.includes(lib),'embedded library and source match');
ok(lib.includes('chartProjects,chartProject'),'local chart access');
ok(source.includes("filter='progressions'"),'show progressions by default');
const songs=[{id:1,title:'Above All',artist:'Michael W Smith',sections:[],notes:{lines:[]},source:{}},{id:2,title:'All Honour (Ron Kenoly)',artist:'Ron Kenoly',sections:[{part:'Chorus',chords:'4 5 1'}],notes:{lines:['My notes']},source:{}}];
const win={BassSongReferenceData:{version:'RC219',songs}},doc={readyState:'loading',addEventListener(){},getElementById(){return null}};
const store=new Map(),storage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)};
const instrument=source.replace('window.BassChordLibrary={','window.__tests={chartFromProject,keyForProject,simpleChord,storeChart,matchChart,currentSong,everySong};window.BassChordLibrary={');
const context={window:win,document:doc,localStorage:storage,Date,console};vm.createContext(context);vm.runInContext(instrument,context);
const api=win.__tests;
const minor=api.keyForProject({analysis:{baseScale:{rootPc:2,mode:'minor',scaleText:'D Min'}}});
ok(minor.root===5,'relative major');
ok(api.simpleChord({rootPc:2,quality:'min'},minor)==='6m','minor tonic 6m');
const events=[],roots=[0,5,7,0];for(let i=0;i<12;i++)events.push({start:i*2,end:i*2+2,rootPc:roots[i%4],quality:'maj',confidence:.93});
const project={format:'Bass Stem Studio Project',projectName:'Above All - Michael W Smith',analysis:{baseScale:{rootPc:0,mode:'major',scaleText:'C major'},tempoBpm:120,structure:{segments:[{name:'Intro',start:0,end:8},{name:'Verse 1',start:8,end:16},{name:'Chorus 1',start:16,end:24},{name:'Section 4',start:24,end:32,uncertain:true}]},chords:events}};
const chart=api.chartFromProject(project);
ok(chart.sections.length===3,'known named sections');
ok(chart.sections.every(s=>s.chords==='1 4 5 1'),'simple numbers');
ok(chart.sections.every(s=>s.source==='saved-project'),'draft label');
ok(!chart.key,'no fixed display key');
ok(api.matchChart(chart).id===1,'safe song match');
(async()=>{
 ok(await api.storeChart(chart,{filename:'Above All.bassstudio',size:4200,modified:2})==='filled','fills blank song');
 ok(api.currentSong(1).sections.length===3,'numbers saved');
 ok(await api.storeChart(chart,{filename:'Above All.bassstudio',size:4200,modified:2})==='already','no duplicate');
 ok(await api.storeChart({...chart,title:'All Honor - Ron Kenoly'},{filename:'All Honor.bassstudio',size:7000,modified:1})==='already','do not overwrite');
 ok(await api.storeChart({...chart,title:'New Song - Singer'},{filename:'New Song.bassstudio',size:7000,modified:4})==='added','add new song');
 ok(api.everySong().length===3,'add to local song list');
 console.log('RC219 checks passed: '+checks);
})().catch(e=>{console.error(e);process.exitCode=1;});
