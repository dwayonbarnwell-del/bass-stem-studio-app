const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('ai-source/worship-live.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const match=html.match(/<script id="rc208-worship-live">([\s\S]*?)<\/script>/);
assert(match,'The church live module must be in the app.');
assert.equal(match[1].trim(),source.trim(),'The maintained code must match the installed app.');
const context={window:{},Float32Array,Float64Array,Math,Map,Number,Object,Array};
vm.createContext(context);vm.runInContext(source,context);
const dsp=context.window.BassWorshipLive;
function frames(fn,n=50){const values=new Float32Array(n*88);for(let i=0;i<n;i++)for(const [m,v] of fn(i))values[i*88+m-21]=v;return {values,frames:n,pitches:88};}
const chord=(notes,lead=[])=>frames(()=>[...notes.map(m=>[m,.8]),...lead]);
assert.equal(dsp.analyse(chord([48,52,55])).chord,'C');
assert.equal(dsp.analyse(chord([45,48,52])).chord,'Am');
assert.equal(dsp.analyse(chord([52,55,59])).chord,'Em');
assert.equal(dsp.analyse(frames(()=>[])).chord,'—');
assert.equal(dsp.analyse(frames(()=>[[69,.88]])).chord,'—','Single notes must not appear as chords.');
assert.equal(dsp.analyse(frames(i=>[[60,64,67][i%3],.8])).chord,'—','Sequential melody must not look like a chord.');
const singer=dsp.analyse(frames(i=>[[48,.65],[52,.65],[55,.65],[[72,.94],[74,.94],[76,.94]][Math.floor(i/18)%3]]));
assert.equal(singer.chord,'C');assert(singer.lead&&singer.lead.midi>=70,'Prefer the prominent upper singing line over lower band notes.');
const deep=dsp.analyse(frames(()=>[[53,.85]]));assert.equal(deep.lead?.note,'F3','A lower singer must still be possible.');
const follower=dsp.createFollower();
assert.equal(follower.update({chord:'C',confidence:.7},1).chord,'—');
assert.equal(follower.update({chord:'C',confidence:.7},2).chord,'C');
assert.equal(follower.update({chord:'G',confidence:.7},3).chord,'C');
assert.equal(follower.update({chord:'G',confidence:.7},4).chord,'G');
assert.equal(follower.update({chord:'—',confidence:0},8).chord,'—');
follower.clear();
assert.equal(follower.update({chord:'E',confidence:.98},1).chord,'E','A strong chord should not wait for another inference.');
assert(html.includes('Church: lead singer + basic chords'));
assert(html.includes("Lead note: "));
console.log('PASS RC208: church lead, simple chords, smooth changes, silence, lower voices, and app integration.');
